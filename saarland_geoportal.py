class LayerProcessingSignals(QObject):
    """Signals for communicating between worker threads and main thread."""

    layer_processed = pyqtSignal(str, bool, str, object)
    progress_updated = pyqtSignal(int)


class LayerWorker(QRunnable):
    """Worker thread for processing individual layers."""

    def __init__(self, layer_data, plugin_instance, worker_id):
        super().__init__()
        self.layer_data = layer_data
        self.plugin = plugin_instance
        self.worker_id = worker_id
        self.signals = LayerProcessingSignals()

    def run(self):
        """Process a single layer in a worker thread."""
        name = self.layer_data["name"]
        title = self.layer_data["title"]
        srs_list = self.layer_data.get("srs", [])
        base_url = self.layer_data["url"]
        service_type = self.layer_data.get("service_type", "WMS")

        logger.info(
            f"Worker {self.worker_id}: Processing layer: {name} ({service_type})"
        )

        try:
            layer = self.plugin._process_single_layer(self.layer_data)
            if layer and layer.isValid():
                self.signals.layer_processed.emit(name, True, "", layer)
            else:
                error = (
                    layer.error().message()
                    if layer and layer.error()
                    else "Unknown error"
                )
                self.signals.layer_processed.emit(name, False, error, None)
        except Exception as e:
            error_msg = str(e)
            logger.error(
                f"Worker {self.worker_id}: Exception processing layer '{name}': {error_msg}"
            )
            self.signals.layer_processed.emit(name, False, error_msg, None)


