    def load_all_sources_silent(self):
        """Load all sources without updating the main dialog's status label."""
        total_loaded = 0
        errors = []

        def load_recursive(parent_item):
            nonlocal total_loaded, errors
            for i in range(
                parent_item.childCount()
                if hasattr(parent_item, "childCount")
                else self.layers_tree.topLevelItemCount()
            ):
                if hasattr(parent_item, "child"):
                    item = parent_item.child(i)
                else:
                    item = self.layers_tree.topLevelItem(i)

                item_type = item.data(0, Qt.UserRole + 2)

                if item_type == "service":

                    service_data = item.data(0, Qt.UserRole)
                    if service_data and not service_data.get("is_loaded", False):
                        try:

                            self.loading_status_label.setText(
                                "Loading: {}...".format(item.text(0))
                            )
                            QtWidgets.QApplication.processEvents()

                            count = self.load_layers_for_service(item, service_data)
                            total_loaded += count
                        except Exception as e:
                            errors.append("{}: {}".format(item.text(0), str(e)))
                elif item_type == "category":

                    load_recursive(item)

        load_recursive(self.layers_tree)

        if errors:
            self.status_label.setText(
                "Loaded {} layers with some errors. See console for details.".format(
                    total_loaded
                )
            )
            for error in errors:
                print("Error loading source:", error)
        else:
            self.status_label.setText(
                "Successfully loaded {} layers from all sources. Check layers to import.".format(
                    total_loaded
                )
            )

