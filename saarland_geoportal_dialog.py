    def update_parent_check_state(self, item):
        """Update parent's check state based on children's states."""
        parent = item.parent()
        if parent is None:
            return

        checked_count = 0
        unchecked_count = 0
        partial_count = 0

        for i in range(parent.childCount()):
            child = parent.child(i)
            state = child.checkState(0)
            if state == Qt.Checked:
                checked_count += 1
            elif state == Qt.Unchecked:
                unchecked_count += 1
            else:
                partial_count += 1

        total = parent.childCount()
        new_state = None
        if checked_count == total:
            new_state = Qt.Checked
        elif unchecked_count == total:
            new_state = Qt.Unchecked
        else:
            new_state = Qt.PartiallyChecked

        if parent.checkState(0) != new_state:
            parent.setCheckState(0, new_state)

            self.update_parent_check_state(parent)

